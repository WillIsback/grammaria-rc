#!/usr/bin/env python3
"""Generates src/morfologik/unicode_tables.rs from the JDK's Unicode data.

usage: gen_unicode_tables.py <nfd.txt> <otheralpha.txt> <letternumbers.txt> <output.rs>

The three inputs are the outputs of `Oracle nfd`, `Oracle otheralpha` and
`Oracle letternumbers` (tools/morfologik/Oracle.java).
"""
import sys


def read(path):
    with open(path) as f:
        return [tuple(int(x, 16) for x in line.split()) for line in f if line.strip()]


nfd, other, nl, out = read(sys.argv[1]), read(sys.argv[2]), read(sys.argv[3]), sys.argv[4]


def table(name, doc, rows, per_line):
    lines = [doc, "#[rustfmt::skip]", "pub(super) static %s: [(u16, u16); %d] = [" % (name, len(rows))]
    for i in range(0, len(rows), per_line):
        lines.append("    " + " ".join("(0x%04X, 0x%04X)," % r for r in rows[i:i + per_line]))
    lines.append("];")
    return "\n".join(lines)


text = """//! Unicode data tables for [`super::unicode`].
//!
//! Generated by `tools/morfologik/gen_unicode_tables.py` from the character
//! data of JDK 21 (Unicode 15.0, Unicode licence), so that the speller
//! classifies characters as `java.lang.Character` and `java.text.Normalizer`
//! do. Basic Multilingual Plane only: Java's speller works on UTF-16 units.
//! Do not edit by hand.

"""
text += table(
    "NFD_FIRST",
    "/// `(c, first)`: the first UTF-16 unit of the canonical decomposition (NFD)\n"
    "/// of `c`, for every character where it differs from `c`. Hangul syllables\n"
    "/// are not listed (they decompose arithmetically). Sorted by `c`.",
    nfd, 6)
text += "\n\n"
text += table(
    "OTHER_ALPHABETIC",
    "/// Inclusive ranges of characters that have the `Alphabetic` property but\n"
    "/// are neither letters (`L*`) nor letter numbers (`Nl`): combining vowel\n"
    "/// signs, circled letters... Sorted.",
    other, 6)
text += "\n\n"
text += table(
    "LETTER_NUMBERS",
    "/// Inclusive ranges of the letter numbers (general category `Nl`). Sorted.",
    nl, 6)
text += "\n"
with open(out, "w") as f:
    f.write(text)
print(len(nfd), "decompositions,", len(other), "other-alphabetic ranges,", len(nl), "letter-number ranges")
